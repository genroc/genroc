package main

// The genroc-ui reference RUNS genroc-ui, for its flags and for ui.yaml's schema: it lives in
// the ui module, which this one cannot import.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func writeUIReference(dir, genrocUI string) error {
	flags, err := readServerFlags(genrocUI)
	if err != nil {
		return err
	}
	out, err := exec.Command(genrocUI, "config-schema").Output()
	if err != nil {
		return fmt.Errorf("%s config-schema: %w", genrocUI, err)
	}
	schema, err := parseSchema(out, "ui.yaml")
	if err != nil {
		return err
	}
	page, err := renderUIReference(flags, schema)
	if err != nil {
		return err
	}
	path := filepath.Join(dir, "genroc-ui.md")
	if err := os.WriteFile(path, []byte(page), 0644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d flags)\n", path, len(flags))
	return nil
}

func renderUIReference(flags []serverFlag, schema jsonSchema) (string, error) {
	sections := []defSection{
		{title: "ui.yaml", intro: "The file `--config` or `$GENROC_UI_CONFIG` names. Without one there is no login.",
			fields: fieldsOf(schema)},
		{title: "login", fields: fieldsOf(defOf(schema, "Login"))},
		{title: "login.providers", intro: "Each entry:", fields: fieldsOf(defOf(schema, "Provider"))},
		{title: "login.passwords", intro: "Each entry:", fields: fieldsOf(defOf(schema, "Password"))},
		{title: "token", intro: "genroc verifies what genroc-ui mints, so these must match its `--jwt-*` flags.",
			fields: fieldsOf(defOf(schema, "Token"))},
	}
	for _, s := range sections {
		if len(s.fields) == 0 {
			return "", fmt.Errorf("genroc-ui reference: section %q came out empty; ui.yaml's schema changed shape", s.title)
		}
	}

	b := &strings.Builder{}
	fmt.Fprintf(b, "---\ntitle: Genroc UI\ndescription: %s\norder: 7\n---\n",
		yamlString("Every flag of the genroc-ui binary, and every key of its ui.yaml."))
	fmt.Fprint(b, "\n<!-- Generated by `make docs-reference` from `genroc-ui -h` and `genroc-ui config-schema`. Do not edit. -->\n")
	fmt.Fprint(b, "\n## Flags\n")
	for _, f := range flags {
		flagEntry(b, f)
	}
	for _, s := range sections {
		fmt.Fprintf(b, "\n## %s\n", s.title)
		if s.intro != "" {
			fmt.Fprintf(b, "\n%s\n", escapeProse(s.intro))
		}
		fieldTable(b, s.fields)
	}
	return b.String(), nil
}
